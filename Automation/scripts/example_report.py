# -*- coding: utf-8 -*-
"""ตัวอย่างการใช้ docx_core — เอกสารรายงานทั่วไป

รันแล้วได้ไฟล์ example_report.docx ที่ผ่านด่านตรวจครบทุกข้อ
ใช้เป็นแม่แบบตอนเริ่มงานใหม่ ก๊อปไฟล์นี้ไปแก้เนื้อหา ไม่ต้องเขียนโครงใหม่

ข้อตกลงการพิมพ์ที่ใช้ (SPEC_TH_ACADEMIC)
  - TH Sarabun New 16 pt ทั้งเอกสาร ระยะบรรทัดเดี่ยว ไม่มีระยะห่างระหว่างย่อหน้า
  - จัดกระจายแบบไทย ปล่อยให้ Word ตัดคำเอง ไม่กด Enter กลางย่อหน้า
  - หัวเรื่องขนาดเท่าเนื้อความ ต่างกันที่ตัวหนา ยกเว้นหัวบทและชื่อบท 18 pt กึ่งกลาง
  - ลำดับชั้นใช้เยื้องบรรทัดแรก บรรทัดที่สองกลับมาชิดขอบ
  - ชื่อตารางอยู่เหนือตาราง ชื่อภาพอยู่ใต้ภาพ
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx_core import DocBuilder, SPEC_TH_ACADEMIC, verify  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "example_report.docx")


def build():
    b = DocBuilder(SPEC_TH_ACADEMIC)

    b.p("บทที่ 1", "หัวบท")
    b.p("บทนำและความเป็นมาของปัญหา", "ชื่อบท")
    b.blank()

    b.p("ความเป็นมาและความสำคัญ", "หัวข้อ")
    b.body("ย่อหน้าเนื้อความเขียนต่อเนื่องไปเรื่อย ๆ ปล่อยให้โปรแกรมตัดคำและขึ้นบรรทัดใหม่เอง "
           "ไม่ต้องกดปุ่มขึ้นบรรทัดกลางย่อหน้า เพราะเมื่อแก้ข้อความภายหลังแล้วความยาวเปลี่ยนไป "
           "จุดที่กดขึ้นบรรทัดไว้จะค้างอยู่ผิดที่ ทำให้ต้องไล่ลบใหม่ทั้งเอกสาร")
    b.body("ย่อหน้าถัดไปเยื้องบรรทัดแรกเหมือนกัน บรรทัดที่สองเป็นต้นไปกลับมาชิดขอบซ้ายของหน้ากระดาษ "
           "รูปแบบนี้เป็นข้อตกลงประจำเอกสาร ถ้าต้องการเปลี่ยนให้แก้ที่สไตล์ ไม่ใช่แก้ทีละย่อหน้า")
    b.blank()

    b.p("วัตถุประสงค์ของการศึกษา", "หัวข้อ")
    b.p("1. ข้อความของข้อระดับที่หนึ่ง เขียนยาวได้ตามปกติ เมื่อยาวเกินหนึ่งบรรทัด "
        "บรรทัดที่สองจะกลับมาชิดขอบซ้าย", "ข้อ1")
    b.p("1.1 ข้อระดับที่สอง เยื้องเข้ามาอีกขั้นหนึ่ง", "ข้อ2")
    b.p("1) ข้อระดับที่สาม", "ข้อ3")
    b.p("(1) ข้อระดับที่สี่ ระดับลึกที่สุดที่ควรใช้", "ข้อ4")
    b.p("2. ข้อระดับที่หนึ่งข้อถัดไป", "ข้อ1")
    b.blank()

    b.p("ตารางประกอบ", "หัวข้อ")
    b.table(
        "ตารางที่ 1 ตัวอย่างตารางมาตรฐาน",
        ["ลำดับ", "รายการ", "จำนวน", "หมายเหตุ"],
        [(1, "รายการตัวอย่างที่หนึ่ง", 120, "-"),
         (2, "รายการตัวอย่างที่สอง", 340, "-"),
         (3, "รายการตัวอย่างที่สาม", 85, "-")])
    b.blank()
    b.body("ตารางด้านบนตั้งค่าให้หัวตารางซ้ำอัตโนมัติเมื่อตารางยาวข้ามหน้า "
           "และปรับความกว้างพอดีหน้ากระดาษ ชื่อตารางวางไว้เหนือตารางตามหลัก APA")
    b.blank()

    b.p("ภาพประกอบ", "หัวข้อ")
    b.figure_placeholder(
        "1.1", "ตัวอย่างตัวยึดตำแหน่งภาพ",
        "ผังกล่องแนวนอนสามช่วง มีลูกศรเชื่อมต่อเนื่อง",
        labels="กล่อง ก, กล่อง ข, กล่อง ค", center="แกนกลาง",
        source="ออกแบบเองล้วน",
        note="วางตัวยึดตำแหน่งตรงจุดที่เนื้อความพูดถึงภาพนั้น ห้ามกองรวมไว้ท้ายหัวข้อ")

    b.note("บรรทัดสีเทาแบบนี้คือคำแนะนำระหว่างร่าง ลบทิ้งก่อนส่งจริง")

    b.save(OUT)
    return OUT


if __name__ == "__main__":
    path = build()
    ok, items = verify(path)
    print("สร้างไฟล์:", os.path.basename(path))
    for name, passed, val in items:
        print("  %-4s %-32s %s" % ("PASS" if passed else "FAIL", name, val))
    print("ผ่านทั้งหมด" if ok else "ไม่ผ่าน")
